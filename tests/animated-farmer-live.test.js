import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as T from '../kingdom-clash/vendor/three.js';
import {createModel,animateModel,disposeModel} from '../kingdom-clash/model-3d.js';
import {programFor} from '../kingdom-clash/entity-programs.js';
import {LivingWorld} from '../kingdom-clash/living-world/simulation.js';
const card={id:'farmer',name:'The Farmer',type:'commander'};
const params=(options={})=>({clock:1.12,program:programFor(card),vx:0,vy:0,moving:false,activity:0,action:'command',...options});
test('Farmer is a unique sculpted 3D character with an articulated model hierarchy',()=>{
 const g=createModel(card,'farm');
 assert.equal(g.userData.customFarmer,true);
 assert.equal(g.userData.modelStyle,'harvest-hero-mobile-v3');
 const r=g.userData.rig;
 assert.equal(g.userData.limbs.length,4);
 assert.equal(r.legs.length,2);assert.equal(r.arms.length,2);
 for(const key of ['head','hat','beard','pack','staff','carrot']){
   assert.ok(r[key]?.isObject3D,key+' must be a real 3D joint');
 }
 assert.equal(r.head.parent,g);
 assert.equal(r.hat.parent,r.head);
 assert.equal(r.beard.parent,r.head);
 assert.ok(r.staff.parent===r.arms[0]);
 let vertices=0,meshes=0,flat=0;
 g.traverse(node=>{if(!node.isMesh)return;meshes++;vertices+=node.geometry.attributes.position.count;if(['PlaneGeometry','CircleGeometry'].includes(node.geometry.type))flat++;});
 assert.ok(vertices>1000,'needs actual sculpted surfaces');
 assert.ok(meshes>10,'character has detailed dimensional features');
 assert.equal(flat,0,'no billboard substitutes');
 const bounds=new T.Box3().setFromObject(g),size=bounds.getSize(new T.Vector3());
 assert.ok(size.y>2&&size.x>1&&size.z>.7);
 disposeModel(g);
});
test('Farmer idle, walk, harvest, attack, hit and reduced-motion poses animate mesh joints',()=>{
 const g=createModel(card,'farm'),r=g.userData.rig;
 animateModel(g,params(),false);assert.equal(g.userData.animationState,'idle');
 const idleLeg=r.legs[0].rotation.x,idleStaff=r.arms[0].rotation.x;
 animateModel(g,params({moving:true,vx:1,clock:1.18,action:'walk'}),false);
 assert.equal(g.userData.animationState,'walk');
 assert.notEqual(r.legs[0].rotation.x,idleLeg);
 assert.ok(Math.abs(r.legs[0].rotation.x-r.legs[1].rotation.x)>.1);
 assert.ok(g.userData.bob>0);
 animateModel(g,params({activity:.32,action:'harvest'}),false);
 assert.equal(g.userData.animationState,'harvest');
 assert.ok(Math.abs(r.arms[1].rotation.x)>.1);
 animateModel(g,params({activity:.33,action:'attack'}),false);
 assert.equal(g.userData.animationState,'attack');
 assert.ok(Math.abs(r.arms[0].rotation.x-idleStaff)>.4,'pitchfork attack is visibly different');
 animateModel(g,params({activity:.4,action:'hit'}),false);
 assert.equal(g.userData.animationState,'hit');assert.ok(r.head.rotation.z>.02);
 animateModel(g,params({moving:true,vx:1,action:'attack',activity:.3}),true);
 assert.equal(g.userData.animationState,'rest');
 assert.equal(g.userData.bob,0);
 assert.equal(r.legs[0].rotation.x,0);
 assert.equal(r.legs[1].rotation.x,0);
 disposeModel(g);
});
test('live Farmer command moves his actual position and holds without teleporting',()=>{
 const world=new LivingWorld({seed:42,rival:false}),farmer=world.entities.find(e=>e.card.id==='farmer');
 assert.ok(farmer);
 const start={x:farmer.x,z:farmer.z};
 const targets=[[start.x+9,start.z],[start.x+7,start.z+3],[start.x-8,start.z+2],[start.x,start.z-8]];
 const target=targets.map(([x,z])=>({x,z})).find(p=>world.terrain.walkable(p.x,p.z,world.structures));
 assert.ok(target,'choose a walkable target');
 const cmd=world.command(farmer.id,'move',target);assert.equal(cmd.ok,true);
 world.paused=false;
 for(let i=0;i<120;i++)world.step(.05);
 const moved=Math.hypot(farmer.x-start.x,farmer.z-start.z);
 assert.ok(moved>1,'Farmer must move by real world units when ordered; moved '+moved.toFixed(2));
 assert.ok(Math.hypot(farmer.x-target.x,farmer.z-target.z)<Math.hypot(start.x-target.x,start.z-target.z));
 assert.equal(world.command(farmer.id,'hold').ok,true);
 const stop={x:farmer.x,z:farmer.z};
 for(let i=0;i<30;i++)world.step(.05);
 assert.ok(Math.hypot(farmer.x-stop.x,farmer.z-stop.z)<.001,'hold keeps position fixed');
 assert.equal(world.command(farmer.id,'auto').ok,true);
 assert.equal(farmer.order,null);
});
